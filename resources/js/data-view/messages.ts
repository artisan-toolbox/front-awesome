export type DataViewMessage = keyof typeof english;
export function useDataViewText() {
    const localization = inject(localizationKey, undefined);
    return (
        key: DataViewMessage,
        values: Record<string, string | number> = {},
        count?: number,
    ): string => {
        const name = `front-awesome::data-view.${key}`;
        const params = count === undefined ? values : { ...values, count };
        if (localization) {
            const translated = localization.t(name, params);
            if (translated !== name) return translated;
        }
        const line = english[key];
        return replaceMessage(
            count === undefined ? line : chooseMessage(line, count, 'en'),
            params,
        );
    };
}
